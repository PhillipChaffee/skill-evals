// The pieces that every generated docs page is written with.
/** The fence of a code block. */
export const FENCE = "```";
/**
 * Marks text as code.
 * @param text - Any text.
 * @returns The text in backticks.
 */
export const code = (text: string): string => `\`${text}\``;

/**
 * Writes a Markdown table.
 * @param head - What each column is called.
 * @param rows - Each line under the titles. A vertical bar in a cell is escaped, so it cannot end the cell.
 * @returns The line of titles, the separator line, and one line for each row.
 */
export function table(head: string[], rows: string[][]): string {
  const line = (cells: string[]): string =>
    `| ${cells.map((cell) => cell.replaceAll("|", String.raw`\|`)).join(" | ")} |`;
  return [line(head), line(head.map(() => "---")), ...rows.map(line)].join(
    "\n",
  );
}

/**
 * Starts a generated page.
 * @param front - The page's title and description for its front matter.
 * @param front.title - The title, which the site shows as the page's heading.
 * @param front.description - One sentence for search engines and link previews.
 * @param source - The source file that holds the table, relative to the repository root.
 * @returns The front matter and the note that names the source.
 */
export const header = (
  front: { title: string; description: string },
  source: string,
): string => `---
title: ${front.title}
description: ${front.description}
editUrl: false
---

<!-- Generated by "npm run docs:reference". Edit ${source}, not this file. -->

_This page is generated from ${source}, so it says what the tool does._`;

/** One reference page of the docs site, written from the tables in the code. */
export interface ReferencePage {
  /** Where the page goes, relative to the docs content directory. */
  file: string;
  /** The whole file: front matter, the note that says it is generated, and the body. */
  markdown: string;
}
